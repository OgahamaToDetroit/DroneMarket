def back_derive(value: float, pct: float, prefer: float | None = None):
    """ถอดค่าปีก่อนหน้าจากคอลัมน์ %เปลี่ยนแปลง ที่ DBD แสดงคู่มากับปี 2564

    DBD ใช้สูตร %change = (ปีนี้ − ปีก่อน) / |ปีก่อน| × 100
    (ตรวจกับปีที่มีข้อมูลครบทั้งสองปีแล้วตรงทุกรายการ — รวมกรณีปีก่อนติดลบ)

    🚨 กับดัก: ตัวหารเป็น **ค่าสัมบูรณ์** สมการย้อนกลับจึงมี **สองราก**
       (ปีก่อนเป็นบวก / ปีก่อนเป็นลบ) และทั้งคู่ผ่านการตรวจเครื่องหมายในตัวเอง
       ถ้าเผลอหยิบรากแรกมาใช้จะได้คำตอบที่ "ดูสมเหตุสมผล" แต่เล่าเรื่องกลับด้าน
       เคยพลาดมาแล้ว: ส่วนของผู้ถือหุ้นปี 2563 ได้ +4,908,812 (รากบวก)
       ทั้งที่ค่าจริงคือ −1,593,501 — ทำให้อ่านว่า "ปี 2563 แข็งแรงแล้วพังปี 2564"
       ทั้งที่ความจริงคือ "ส่วนทุนติดลบมาตั้งแต่ก่อนปี 2563"

    รายการที่มีสองราก **ต้องส่ง `prefer` มาตัดสินจากสมการอื่นที่เป็นอิสระ**:
      · ส่วนของผู้ถือหุ้น → ใช้ ส่วนทุนปี 2564 − กำไรสุทธิปี 2564
      · กำไรสุทธิ        → ใช้ รายได้รวมปี 2563 − รายจ่ายรวมปี 2563
    ถ้าไม่ส่ง `prefer` มาและมีสองราก จะคืน None — ยอมไม่ตอบดีกว่าตอบผิด

    คืน (ค่าที่เลือก, รากทั้งหมด)
    """
    p = pct / 100.0
    roots = []
    for sign in (1, -1):
        # value − prev = p × |prev| = p × sign × prev   (sign = เครื่องหมายของ prev)
        denom = 1 + p * sign
        if abs(denom) < 1e-9:
            continue
        prev = value / denom
        if (prev > 0) == (sign > 0) and abs(prev) > 1e-6:
            roots.append(prev)
    if len(roots) == 1:
        return roots[0], roots
    if not roots:
        return None, roots
    if prefer is None:
        return None, roots
    return min(roots, key=lambda r: abs(r - prefer)), roots


