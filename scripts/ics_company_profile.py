# ------------------------------------------------------------------ e-GP sweep
def _get(url: str, tries: int = 3):
    for i in range(tries):
        try:
            return json.load(urllib.request.urlopen(url, timeout=240))
        except Exception:
            if i == tries - 1:
                raise
            time.sleep(3)


def sweep_egp() -> pd.DataFrame:
    """กวาดทุกไฟล์ e-GP หา ICS จาก **ชื่อ** และ **เลขนิติบุคคล** สองทางแยกกัน

    ทำสองทางเพราะทางเดียวเชื่อไม่ได้:
      · ชื่อ  — ถ้ามีปีไหนสะกดติดกันไม่มีช่องว่าง q= จะมองไม่เห็น
      · เลข  — ถ้าปีไหน Excel ทำพังคนละแบบก็จะมองไม่เห็นเหมือนกัน
    ถ้าสองทางได้ผลตรงกัน แปลว่าครบจริง (รอบนี้ตรงกันทั้ง 5 สัญญา)
    """
    rows, by_name, by_id = {}, set(), set()
    for year, pkg in PACKAGES.items():
        res = _get(f"{PKG_SHOW}?{urllib.parse.urlencode({'id': pkg})}")["result"]
        files = [(r["name"], r["id"]) for r in res["resources"]
                 if (r.get("format") or "").upper() == "CSV"]
        for fname, rid in files:
            for term, bucket in ((NAME_TOKEN, by_name), (JURISTIC_ID, by_id),
                                 (JURISTIC_BROKEN, by_id)):
                q = {"resource_id": rid, "q": term, "limit": 500}
                r = _get(f"{DS_SEARCH}?{urllib.parse.urlencode(q)}")["result"]
                for rec in r.get("records", []):
                    blob = " ".join(str(v) for v in rec.values())
                    if NAME_TOKEN not in blob and JURISTIC_ID not in blob:
                        continue        # q= ตอบกว้างกว่าที่ขอ ต้องกรองซ้ำเอง
                    if str(year) == "2568":
                        rec = remap_2568(rec)
                    key = (rec.get("รหัสโครงการ"), fname)
                    bucket.add(key)
                    rec["_ปีงบ"] = year
                    rec["_ไฟล์"] = fname
                    rows[key] = rec
        print(f"  กวาดปีงบ {year} ({len(files)} ไฟล์) — สะสม {len(rows)} สัญญา", flush=True)

    # ห้ามเขียนตายว่า "สองทางตรงกัน" — ให้ตรวจแล้วรายงานตามจริง
    if by_name == by_id:
        print(f"  ✅ ค้นด้วยชื่อ และ ค้นด้วยเลขนิติบุคคล ได้ผลตรงกันทั้ง {len(rows)} สัญญา")
    else:
        print(f"  ⚠️ สองวิธีได้ผลไม่ตรงกัน — เจอเฉพาะทางชื่อ {len(by_name - by_id)} "
              f"· เฉพาะทางเลข {len(by_id - by_name)} → ต้องไล่ดูด้วยตา")
    return pd.DataFrame(list(rows.values()))


