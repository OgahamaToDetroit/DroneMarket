def remap_2568(rec: dict) -> dict:
    """ย้ายค่ากลับเข้าคอลัมน์ที่ถูกต้องสำหรับไฟล์ปีงบ 2568

    🚨 กับดัก: เขียนเป็น dict comprehension บรรทัดเดียวไม่ได้
        {SHIFT_2568.get(k, k): v for k, v in rec.items()}
    เพราะชื่อคอลัมน์ปลายทางบางตัว (เช่น `งบสัญญา(บาท)`) **มีอยู่ในต้นทางด้วย**
    และอยู่ถัดจากตัวที่ map มาทับ dict จึงเอาค่า None ของตัวหลังไปทับค่าที่ถูกต้อง
    ผลคือมูลค่าสัญญาหายกลายเป็น NaN โดยไม่มี error ให้เห็น
    (เจอตอนสัญญาปี 2568 ขึ้นว่า 'nan บาท' ทั้งที่ค่าจริงคือ 136,809)
    """
    targets = set(SHIFT_2568.values())
    out = {k: v for k, v in rec.items()
           if k not in SHIFT_2568 and k not in targets and not k.endswith("(Eng)")}
    for src, dst in SHIFT_2568.items():
        out[dst] = rec.get(src)
    return out

